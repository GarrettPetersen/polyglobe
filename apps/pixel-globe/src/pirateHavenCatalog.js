export function pirateHavenCityRecords(cities) {
  const byId = new Map(cities.map(city => [city.cityId, city]));
  return PIRATE_HAVEN_SPECS.map(spec => {
    const template = byId.get(spec.templateCityId);
    if (!template) throw new Error(`Pirate haven ${spec.id} is missing its regional template ${spec.templateCityId}`);
    const architectureStyle = spec.architectureStyle;
    const record = { ...template,
      pirateCulture: spec.pirateCulture || "pirate",
      territoryId: spec.territoryId,
      ...(spec.pirateCulture === "wokou" ? { nameCulture: "japanese" } : {}),
      pirateArchitectureStyle: architectureStyle,
      portraitRegion: spec.pirateCulture === "wokou" ? "japan" : undefined, cityId: spec.id, portId: spec.id,
      city: spec.name, displayCity: spec.name, country: spec.country,
      lat: spec.lat, lon: spec.lon, factionId: "pirate", isPirateHideout: true,
      portAlias: spec.name, population: 1200, settlementType: "village",
      coastalIntent: true, lakeIntent: false, waterAccess: "ocean",
      isFactionCapital: false, capitalOfFactionId: null, declaredCapitalFactionId: null,
      playerHomeExcluded: true, foreignSettlements: [] };
    delete record.placementLat;
    delete record.placementLon;
    delete record.islandSettlement;
    delete record.colonialFounding;
    return record;
  });
}
