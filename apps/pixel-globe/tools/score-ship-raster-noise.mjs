import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { createCanvas, loadImage } from "../../../examples/globe-demo/node_modules/canvas/index.js";
import { scoreShipRasterNoise } from "../src/shipRasterNoise.js";

const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(appRoot, "../..");
const manifestPath = join(appRoot, "public/assets/vehicles/unity-ships/manifest.json");
const reportJsonPath = join(appRoot, "docs/ship-reference/raster-noise.json");
const reportMarkdownPath = join(appRoot, "docs/ship-reference/raster-noise.md");
const reviewSheetPath = join(appRoot, "docs/ship-reference/raster-noise-review.png");

const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
if (!Array.isArray(manifest.ships) || manifest.ships.length === 0) {
  throw new Error("Ship raster noise scoring requires a populated production manifest");
}

const results = [];
const shipsBySlug = new Map();
for (const ship of manifest.ships) {
  shipsBySlug.set(ship.slug, ship);
  const sheetPath = resolve(repoRoot, ship.files.sheet);
  const image = await loadImage(sheetPath);
  const canvas = createCanvas(image.width, image.height);
  const context = canvas.getContext("2d");
  context.imageSmoothingEnabled = false;
  context.drawImage(image, 0, 0);
  const imageData = context.getImageData(0, 0, image.width, image.height);
  results.push({
    slug: ship.slug,
    label: ship.label,
    sourceTitle: ship.sourceTitle,
    ...scoreShipRasterNoise({
      data: imageData.data,
      width: image.width,
      height: image.height,
      frameSize: ship.frameSize,
      headingCount: ship.headings,
      sheetColumns: ship.sheetCols
    })
  });
}
results.sort((a, b) => b.score - a.score || a.label.localeCompare(b.label));

writeFileSync(reportJsonPath, `${JSON.stringify({
  generatedBy: "tools/score-ship-raster-noise.mjs",
  method:
    "Weighted one-pixel color reversals, checkerboards, isolated contrasting flecks, and local color diversity inside fully opaque 3x3 sprite regions. Transparent silhouette edges and broad material boundaries are excluded.",
  ships: results.map(({ frames, ...result }) => result)
}, null, 2)}\n`);

const lines = [
  "# Ship Raster Noise",
  "",
  "Generated by `npm run analyze:ship-raster-noise`.",
  "",
  "The score measures one-pixel color reversals, checkerboards, isolated flecks, and local " +
    "color diversity only inside fully opaque 3x3 regions. This avoids penalizing legitimate " +
    "silhouettes, masts, rigging, small ship size, and broad material boundaries. " +
  "It is a prioritization aid; final changes still require visual review.",
  "",
  "![Four-heading review of the twelve highest-scoring ships](raster-noise-review.png)",
  "",
  "| Rank | Ship | Score | Micro reversals | Checkerboards | Flecks | Local diversity |",
  "| ---: | --- | ---: | ---: | ---: | ---: | ---: |",
  ...results.map((result, index) => (
    `| ${index + 1} | ${result.label} (\`${result.slug}\`) | ${result.score.toFixed(2)} | ` +
    `${percent(result.microReversalRatio)} | ${percent(result.checkerboardRatio)} | ` +
    `${percent(result.isolatedFleckRatio)} | ` +
    `${percent(result.localColorDiversity)} |`
  )),
  ""
];
writeFileSync(reportMarkdownPath, lines.join("\n"));
await writeReviewSheet(results.slice(0, 12));

for (const [index, result] of results.slice(0, 12).entries()) {
  console.log(`${String(index + 1).padStart(2)}. ${result.label.padEnd(28)} ${result.score.toFixed(2)}`);
}

function percent(value) {
  return `${(value * 100).toFixed(1)}%`;
}

async function writeReviewSheet(rankedShips) {
  const columns = 3;
  const rows = Math.ceil(rankedShips.length / columns);
  const itemWidth = 440;
  const itemHeight = 150;
  const canvas = createCanvas(itemWidth * columns, itemHeight * rows);
  const context = canvas.getContext("2d");
  context.imageSmoothingEnabled = false;
  context.fillStyle = "#171820";
  context.fillRect(0, 0, canvas.width, canvas.height);
  context.font = "18px sans-serif";
  context.textBaseline = "top";

  for (const [index, result] of rankedShips.entries()) {
    const ship = shipsBySlug.get(result.slug);
    if (!ship) throw new Error(`Noise review is missing manifest data for ${result.slug}`);
    const image = await loadImage(resolve(repoRoot, ship.files.sheet));
    const originX = (index % columns) * itemWidth;
    const originY = Math.floor(index / columns) * itemHeight;
    context.fillStyle = "#eee0bd";
    context.fillText(`${index + 1}. ${result.label}  ${result.score.toFixed(2)}`, originX + 12, originY + 10);
    for (const [sampleIndex, heading] of [0, 8, 16, 24].entries()) {
      const sourceX = (heading % ship.sheetCols) * ship.frameSize;
      const sourceY = Math.floor(heading / ship.sheetCols) * ship.frameSize;
      context.drawImage(
        image,
        sourceX,
        sourceY,
        ship.frameSize,
        ship.frameSize,
        originX + 12 + sampleIndex * 104,
        originY + 40,
        ship.frameSize * 2,
        ship.frameSize * 2
      );
    }
  }

  writeFileSync(reviewSheetPath, canvas.toBuffer("image/png"));
}
