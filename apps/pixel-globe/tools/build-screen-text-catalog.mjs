import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { extractScreenTextSourceCatalog } from "./screen-text-source-catalog.mjs";

const APP_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE_ROOT = path.join(APP_ROOT, "src");
const OUTPUT_PATH = path.join(SOURCE_ROOT, "screenTextCatalog.js");
const baseEnglish = await extractBaseEnglishValues(path.join(SOURCE_ROOT, "localization.js"));
const templates = extractScreenTextSourceCatalog(SOURCE_ROOT)
  .filter((template) => !baseEnglish.has(template));

await mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
await writeFile(OUTPUT_PATH, renderModule(templates));
process.stdout.write(`Screen text catalog: ${templates.length} templates in ${OUTPUT_PATH}\n`);

async function extractBaseEnglishValues(sourcePath) {
  const source = await readFile(sourcePath, "utf8");
  const sourceFile = ts.createSourceFile(
    path.basename(sourcePath),
    source,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.JS
  );
  let englishObject = null;
  function visit(node) {
    if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name) && node.name.text === "ENGLISH") {
      const initializer = node.initializer;
      if (!ts.isCallExpression(initializer) || initializer.expression.getText(sourceFile) !== "Object.freeze" ||
          !ts.isObjectLiteralExpression(initializer.arguments[0])) {
        throw new Error("Base English localization must be an Object.freeze object literal");
      }
      englishObject = initializer.arguments[0];
      return;
    }
    ts.forEachChild(node, visit);
  }
  visit(sourceFile);
  if (!englishObject) throw new Error("Could not find the base English localization catalog");
  const values = new Set();
  for (const property of englishObject.properties) {
    if (!ts.isPropertyAssignment(property) || !ts.isStringLiteralLike(property.initializer)) {
      throw new Error(`Base English localization entry must be a string: ${property.getText(sourceFile)}`);
    }
    values.add(property.initializer.text);
  }
  return values;
}

function renderModule(values) {
  return `// Generated by tools/build-screen-text-catalog.mjs. Do not edit by hand.\n` +
    `export const SCREEN_TEXT_TEMPLATES = Object.freeze(${JSON.stringify(values, null, 2)});\n`;
}
