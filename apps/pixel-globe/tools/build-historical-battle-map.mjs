import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import process from "node:process";

import polygonClipping from "polygon-clipping";

const NATURAL_EARTH_LAND_URL =
  "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_land.geojson";
const OUTPUT_PATH = resolve("src/generated/lepantoLandData.js");
const LEPANTO_BOUNDS = Object.freeze({
  minLongitudeDeg: 19.3,
  maxLongitudeDeg: 22.6,
  minLatitudeDeg: 37.2,
  maxLatitudeDeg: 39.2
});

const inputPath = argumentValue("--input");
const sourceText = inputPath
  ? await readFile(resolve(inputPath), "utf8")
  : await downloadNaturalEarthLand();
const featureCollection = JSON.parse(sourceText);
if (featureCollection?.type !== "FeatureCollection" || !Array.isArray(featureCollection.features)) {
  throw new Error("Natural Earth land source is not a GeoJSON FeatureCollection");
}

const clipPolygon = [[[
  LEPANTO_BOUNDS.minLongitudeDeg,
  LEPANTO_BOUNDS.minLatitudeDeg
], [
  LEPANTO_BOUNDS.maxLongitudeDeg,
  LEPANTO_BOUNDS.minLatitudeDeg
], [
  LEPANTO_BOUNDS.maxLongitudeDeg,
  LEPANTO_BOUNDS.maxLatitudeDeg
], [
  LEPANTO_BOUNDS.minLongitudeDeg,
  LEPANTO_BOUNDS.maxLatitudeDeg
], [
  LEPANTO_BOUNDS.minLongitudeDeg,
  LEPANTO_BOUNDS.minLatitudeDeg
]]];
const clippedPolygons = [];
for (const feature of featureCollection.features) {
  const multiPolygon = geoJsonMultiPolygon(feature?.geometry);
  if (multiPolygon.length === 0) continue;
  clippedPolygons.push(...polygonClipping.intersection(multiPolygon, clipPolygon));
}
const polygons = clippedPolygons
  .map((polygon) => polygon.map((ring) => ring.map(([longitudeDeg, latitudeDeg]) => (
    [roundCoordinate(longitudeDeg), roundCoordinate(latitudeDeg)]
  ))))
  .filter((polygon) => polygon[0]?.length >= 4)
  .sort(comparePolygons);
if (polygons.length < 5) {
  throw new Error(`Lepanto map bake retained too little land geometry: ${polygons.length} polygons`);
}

const generated = `// Generated by tools/build-historical-battle-map.mjs. Do not edit by hand.\n` +
  `// Source: Natural Earth 1:10m land, public domain.\n` +
  `export const LEPANTO_MAP_BOUNDS = Object.freeze(${JSON.stringify(LEPANTO_BOUNDS, null, 2)});\n\n` +
  `export const LEPANTO_LAND_POLYGONS = Object.freeze(${serializeFrozenPolygons(polygons)});\n`;
await mkdir(dirname(OUTPUT_PATH), { recursive: true });
await writeFile(OUTPUT_PATH, generated);
console.log(
  `Wrote ${OUTPUT_PATH} with ${polygons.length} land polygons and ` +
  `${polygons.reduce((total, polygon) => total + polygon.reduce((sum, ring) => sum + ring.length, 0), 0)} vertices.`
);

async function downloadNaturalEarthLand() {
  const response = await fetch(NATURAL_EARTH_LAND_URL);
  if (!response.ok) {
    throw new Error(`Natural Earth land download failed: HTTP ${response.status}`);
  }
  return response.text();
}

function geoJsonMultiPolygon(geometry) {
  if (!geometry) return [];
  if (geometry.type === "Polygon") return [geometry.coordinates];
  if (geometry.type === "MultiPolygon") return geometry.coordinates;
  return [];
}

function serializeFrozenPolygons(polygons) {
  const serialized = polygons.map((polygon) => (
    `Object.freeze([${polygon.map((ring) => (
      `Object.freeze([${ring.map(([longitudeDeg, latitudeDeg]) => (
        `Object.freeze([${longitudeDeg},${latitudeDeg}])`
      )).join(",")}])`
    )).join(",")}])`
  ));
  return `[\n  ${serialized.join(",\n  ")}\n]`;
}

function comparePolygons(a, b) {
  return polygonMinimumLongitude(a) - polygonMinimumLongitude(b) ||
    polygonMinimumLatitude(a) - polygonMinimumLatitude(b);
}

function polygonMinimumLongitude(polygon) {
  return Math.min(...polygon[0].map(([longitudeDeg]) => longitudeDeg));
}

function polygonMinimumLatitude(polygon) {
  return Math.min(...polygon[0].map(([, latitudeDeg]) => latitudeDeg));
}

function roundCoordinate(value) {
  return Math.round(value * 1_000_000) / 1_000_000;
}

function argumentValue(name) {
  const index = process.argv.indexOf(name);
  if (index < 0) return null;
  const value = process.argv[index + 1];
  if (!value || value.startsWith("--")) throw new Error(`${name} requires a path`);
  return value;
}
